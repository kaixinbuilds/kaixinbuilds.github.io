def render(page):
    title_key, body = PAGES[page]
    nav = "\n".join(
        '        <a href="%s"%s data-i18n="%s">%s</a>'
        % (href, CURRENT if href == page else "", key, label)
        for href, key, label in NAV)

    static_title, static_desc = META[page]
    canonical = SITE + "/" + ("" if page == "index.html" else page)

    html = (HEAD
            .replace("__TITLE_KEY__", title_key)
            .replace("__STATIC_TITLE__", static_title)
            .replace("__STATIC_DESC__", static_desc)
            .replace("__CANONICAL__", canonical)
            .replace("__SHARE_IMAGE__", SHARE_IMAGE)
            .replace("__HOME__", CURRENT if page == "index.html" else "")
            .replace("__NAV__", nav + "\n"))
    return html.replace("<!DOCTYPE html>", "<!DOCTYPE html>\n" + BANNER, 1) \
        + '<main id="main">\n' + body + "\n</main>" + TAIL


def write_sitemap():
    """A sitemap and a robots.txt, so search engines can find every page and
    know where the sitemap lives. No lastmod: it would change on every build
    whether or not the content did, for no real benefit."""
    urls = "\n".join(
        "  <url><loc>%s</loc><priority>%s</priority></url>"
        % (SITE + "/" + ("" if p == "index.html" else p), "1.0" if p == "index.html" else "0.8")
        for p in PAGES)
    pathlib.Path("sitemap.xml").write_text(
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
        + urls + "\n</urlset>\n")
    pathlib.Path("robots.txt").write_text(
        "User-agent: *\n"
        "Allow: /\n\n"
        "Sitemap: %s/sitemap.xml\n" % SITE)


if __name__ == "__main__":
    for page in PAGES:
        pathlib.Path(page).write_text(render(page))
        print("built", page)
    write_sitemap()
    print("built sitemap.xml and robots.txt")
