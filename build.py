def render(page):
    title_key, body = PAGES[page]
    nav = "\n".join(
        '        <a href="%s"%s data-i18n="%s">%s</a>'
        % (href, CURRENT if href == page else "", key, label)
        for href, key, label in NAV)

    static_title, static_desc = META[page]
    canonical = SITE + "/" + ("" if page == "index.html" else page)

    html = (HEAD
            .replace("__TITLE_KEY__", title_key)
            .replace("__STATIC_TITLE__", static_title)
            .replace("__STATIC_DESC__", static_desc)
            .replace("__CANONICAL__", canonical)
            .replace("__SHARE_IMAGE__", SHARE_IMAGE)
            .replace("__GA__", GA_SNIPPET.replace("__GA_ID__", GA_MEASUREMENT_ID)
                                if GA_MEASUREMENT_ID else "")
            .replace("__HOME__", CURRENT if page == "index.html" else "")
            .replace("__NAV__", nav + "\n"))
    return html.replace("<!DOCTYPE html>", "<!DOCTYPE html>\n" + BANNER, 1) \
        + '<main id="main">\n' + body + "\n</main>" + TAIL


def write_sitemap():
    """A sitemap and a robots.txt, so search engines can find every page and
    know where the sitemap lives. No lastmod: it would change on every build
    whether or not the content did, for no real benefit."""
    urls = "\n".join(
        "  <url><loc>%s</loc><priority>%s</priority></url>"
        % (SITE + "/" + ("" if p == "index.html" else p), "1.0" if p == "index.html" else "0.8")
        for p in PAGES)
    pathlib.Path("sitemap.xml").write_text(
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
        + urls + "\n</urlset>\n")
    pathlib.Path("robots.txt").write_text(
        "User-agent: *\n"
        "Allow: /\n\n"
        "Sitemap: %s/sitemap.xml\n" % SITE)
    # Every page here is finished HTML. Jekyll has nothing to contribute, and
    # a Jekyll build that fails takes the whole deploy down with it, silently:
    # Pages keeps serving the last good commit and the site simply stops
    # updating. This empty file turns Jekyll off, so Pages just serves files.
    pathlib.Path(".nojekyll").write_text("")


def check_i18n():
    """Every key the pages ask for must exist, and every nlc26 key must be asked
    for. A page that references a deleted key renders the key name at readers,
    which shipped once and was seen. This makes that a build failure instead."""
    i18n = json.loads(pathlib.Path("i18n.json").read_text())
    asked = set()
    for page in PAGES:
        html = pathlib.Path(page).read_text()
        asked |= set(re.findall(r'data-i18n(?:-aria-label)?="([^"]+)"', html))

    missing = sorted(k for k in asked if k not in i18n)
    # Only nlc26 is checked for orphans: the other namespaces are shared across
    # pages and rendered from JSON, so an unused key there is not a mistake.
    orphans = sorted(k for k in i18n
                     if k.startswith("nlc26.") and k not in asked)

    if missing:
        print("\nBUILD FAILED. These keys are on a page but not in i18n.json:")
        for k in missing:
            print("   ", k)
        print("\nEither add them to i18n.json or take them out of build.py.")
        raise SystemExit(1)
    if orphans:
        print("\nUnused nlc26 keys still in i18n.json (harmless, but tidy up):")
        for k in orphans:
            print("   ", k)
    print("i18n keys check out")


